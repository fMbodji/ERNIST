def parse_result_string(result_str, expected_unit='cm'):
  """
  Parses a result string and returns its numerical value, converted to
  expected_unit if the string specifies a different unit (cm or mm).
  Formats handled: "~7.5 - 8.5 cm", "13.5 cm ±1.5 cm", "≈13.5 cm"

  Both cases below mean "missing/unusable data," just via different sentinels:
  - Returns None if result_str is unparseable text, empty/whitespace-only,
    a JSON payload, or None itself.
  - Returns NaN (float('nan')) if result_str was already NaN going in (e.g.
    an empty CSV cell read by pandas) -- passed through, not re-parsed.
  """
  # if result is already a number, return it directly
  if isinstance(result_str, (int, float)):
    return float(result_str)

  # if result_str is a literal None, returns None 
  # (to avoid raising and AttributeError on result_str.strip()
  # instead of just reporting "not parseable")
  if result_str is None:
    return None

  # if not, its either a text string, or empty, or contains only whitespace, or a JSON payload 
  # None of these can be parsed as a numerical distance value, so each case below returns None 
  stripped = result_str.strip()
  if not stripped:
    return None

  if stripped.startswith("{") or stripped.startswith("["):
    return None

  # Pattern checks
  
  # Pattern for range: "~7.5 - 8.5 cm" or "7.5 - 8.5 cm"
  range_matches = list(re.finditer(r'~?(\d+\.?\d*)\s*-\s*(\d+\.?\d*)\s*(cm|mm)', result_str))
  if range_matches:
    range_match = range_matches[-1]
    lower_bound = float(range_match.group(1))
    upper_bound = float(range_match.group(2))
    unit = range_match.group(3)
    median = (lower_bound + upper_bound) / 2.0  # get median for range
    return convert_units(median, unit, expected_unit) 

  # Pattern for tolerance: "13.5 cm ±1.5 cm"
  tolerance_matches = list(re.finditer(r'(\d+\.?\d*)\s*(cm|mm)?\s*±\s*\d+\.?\d*\s*(cm|mm)?', result_str))
  if tolerance_matches:
    tolerance_match = tolerance_matches[-1]
    unit = tolerance_match.group(2) or tolerance_match.group(3) or expected_unit
    return convert_units(float(tolerance_match.group(1)), unit, expected_unit) # get central value for tolerance

  # Pattern for single value: "13.5 cm" or "≈13.5 cm"
  single_value_matches = list(re.finditer(r'≈?(-?\d+\.?\d*)\s*(cm|mm)?', result_str))
  if single_value_matches:
    single_value_match = single_value_matches[-1]
    unit = single_value_match.group(2) or expected_unit
    return convert_units(float(single_value_match.group(1)), unit, expected_unit) # Single value

  return None # if no pattern matches


def get_residual_error (ground_truth, result, expected_unit='cm'):
  """
  For benchmark evaluation purpose
  Computes residual error between the ground truth and result, 
  with both sides converted to expected_unit (default 'cm', 
  pass a different value if a future setup uses a different board.unit).

  Sign convention: residual = ground_truth - result.
    - Positive residual -> the model UNDERESTIMATED the true distance (result < ground_truth).
    - Negative residual -> the model OVERESTIMATED the true distance (result > ground_truth).
  
  Returns NaN if either side couldn't be parsed as a number (e.g. a pointing
  question's JSON ground_truth/result, or genuinely unparseable text).
  """
  parsed_ground_truth = parse_result_string(ground_truth, expected_unit)
  parsed_result = parse_result_string(result, expected_unit)
  if parsed_ground_truth is not None and parsed_result is not None:
    # round(..., 2) instead of an f"{:.2f}" string -- keeps this numeric so
    # the summary stats (.abs().mean()) still work on the column, just
    # trims float noise like 5.1199999999999983 down to a clean 5.12.
    return round(parsed_ground_truth - parsed_result, 2)
  else:
    return np.nan  # pointing-question rows (JSON ground_truth) are handled by check_point_against_mask() instead


def is_pointing_ground_truth(ground_truth):
  """
  returns True if ground_truth is a pointing-question JSON payload (has a mask_path),
  as opposed to a plain distance result string like "11.93cm".
  """
  try:
    parsed = json.loads(ground_truth)
  except (TypeError, json.JSONDecodeError):
    return False
  return isinstance(parsed, dict) and "mask_path" in parsed


CAMERA_VIEW_TO_SUFFIX = {
  "side": "side",
  "mid": "mid",
  "overhead": "ovhd",           # matches distance_questions_generator.py's "ovhd_view" naming
  "far from camera": "far",
}


def build_image_path(image_code, camera_view):
  """
  Derives the image file path from the CSV's Image (e.g. "1A") and Camera
  View (e.g. "Side") columns, matching distance_questions_generator.py's
  naming convention (e.g. images/setup1_side_view.jpg).
  """
  setup_number_match = re.match(r"\d+", str(image_code).strip())
  setup_number = setup_number_match.group() if setup_number_match else str(image_code).strip()

  view_key = str(camera_view).strip().lower()
  view_suffix = CAMERA_VIEW_TO_SUFFIX.get(view_key, view_key)

  return f"images/setup{setup_number}_{view_suffix}_view.jpg"


def find_missing_masks(df):
  """
  Scans a results DataFrame's Ground Truth column for pointing-question rows,
  and reports which of their referenced mask files don't exist yet 
  Uses the SAM_mask_generator.py command to create each one.
  This is how the mask-generation step gets "the answer and label" without having to
  manually cross-reference distance_questions_generator.py's output

  Read-only and fast: just checks Path.exists() on each mask_path already recorded in ground_truth.
  The interactive clicking step still has to be run separately, on purpose

  Returns a list of {"image_path", "mask_path", "label"} dicts, one per
  missing mask (or an empty list if everything needed already exists).
  """
  missing = []
  seen = set()
  for _, row in df.iterrows():
    ground_truth = row["Ground Truth"]
    if not is_pointing_ground_truth(ground_truth):
      continue

    gt = json.loads(ground_truth)
    mask_path = gt["mask_path"]
    label = gt["label"]
    image_path = build_image_path(row["Image"], row["Camera View"])

    key = (image_path, mask_path)  # de-dupe rows that reference the same mask
    if key in seen:
      continue
    seen.add(key)

    if not Path(mask_path).exists():
      missing.append({"image_path": image_path, "mask_path": mask_path, "label": label})

  if missing:
    print(f"{len(missing)} missing mask(s):")
    for m in missing:
      print(f"  Missing: {m['mask_path']}")
      print(f"    Run: python SAM_mask_generator.py --image {m['image_path']} --label {m['label']}")
  else:
    print("All referenced masks already exist.")

  return missing


def check_point_against_mask(image_path, ground_truth, result):
  """
  For pointing questions: parses ground_truth's mask_path + label, 
  parses the model's raw result, and checks whether the returned point for that
  label lands on the ground-truth mask.

  First check: does the model's returned label match the ground-truth
  label? If not, fail immediately without touching the image/mask files.

  Calls straight into verify_point_on_mask.py's pipeline
  (load_mask -> load_response -> gemini_point_to_pixels -> is_point_in_mask).
  
  Returns True/False, or None if it couldn't be checked (missing files, bad JSON).
  """
  gt = json.loads(ground_truth)
  mask_path = gt["mask_path"]
  label = gt["label"]

  try:
    points = load_response(result)
  except json.JSONDecodeError as e:
    print(f"Could not parse model response as JSON: {e}")
    return None

  # First check: label returned by the model vs. the ground-truth label.
  # layer 1: exact match - the common/compliant case (e.g. "D")
  matching = [p for p in points if p.get("label") == label]
  if not matching:
    # layer 2: fallback for verbose labels that still identify the right
    # object, e.g. "the smallest peg (D)" instead of just "D". 
    pattern = re.compile(rf'\b{re.escape(label)}\b', re.IGNORECASE)
    matching = [p for p in points if pattern.search(p.get("label", ""))]
    if matching:
      print(f"Label '{label}' matched via fallback (layer 2) match against: {[p.get('label') for p in matching]!r}")
  if not matching:
    print(f"Label mismatch: model returned {[p.get('label') for p in points]}, expected '{label}'.")
    return False

  if not Path(image_path).exists():
    print(f"Image not found: {image_path}")
    return None
  if not Path(mask_path).exists():
    print(f"Mask not found: {mask_path} (run SAM_mask_generator.py --image {image_path} --label {label} first)")
    return None

  img_width, img_height = Image.open(image_path).size

  mask = load_mask(mask_path)
  if mask is None:
    return None

  raw_point = matching[0]["point"]
  x, y = gemini_point_to_pixels(raw_point, img_width, img_height)
  return is_point_in_mask([x, y], mask, img_width, img_height)


def evaluate_row(row):
  """
  Scores a single results-CSV row: calls check_point_against_mask() for
  pointing questions (JSON ground truth), or get_residual_error() for
  distance questions (plain string ground truth)
  """
  ground_truth = row["Ground Truth"]
  result = row["Response"]

  if is_pointing_ground_truth(ground_truth):
    # Pointing question: check the returned point against its ground-truth mask
    image_path = build_image_path(row["Image"], row["Camera View"])
    on_mask = check_point_against_mask(image_path, ground_truth, result)
    return pd.Series({"Residual Error": np.nan, "Point on Mask?": on_mask})
  else:
    # Distance question: compute the residual error
    residual = get_residual_error(ground_truth, result)
    return pd.Series({"Residual Error": residual, "Point on Mask?": np.nan})


def main():
  parser = argparse.ArgumentParser(
      description="Score a results CSV: residual error for distance questions, "
      "mask-based pass/fail for pointing questions."
  )
  parser.add_argument(
      "--csv", required=True,
      help="Path to the results CSV (expects columns: Question, Type, Camera View, Ground Truth, "
      "Response, Residual Error, Point on Mask?)",
  )
  parser.add_argument("--output", help="Where to save the scored CSV (default: <csv_stem>_scored.csv)")
  args = parser.parse_args()

  # Step 1: load the results CSV into a DataFrame.
  try:
    df = pd.read_csv(args.csv, encoding="utf-8-sig")
  except UnicodeDecodeError:
    print("Note: CSV isn't UTF-8 (likely Excel's default Windows codepage) -- reading as cp1252 instead.")
    df = pd.read_csv(args.csv, encoding="cp1252")

  # strip column names so the lookups below ("Image", "Residual Error", ...) work regardless
  df.columns = df.columns.str.strip() 

  # Step 2: check for pointing-question masks that haven't been created yet.
  # If any are missing, stop here, don't score against known-incomplete
  # ground truth. Re-run this same command once you've generated them.
  missing = find_missing_masks(df)
  if missing:
    print(f"\n{len(missing)} mask(s) need to be created before scoring can proceed.")
    print("Run the command(s) printed above, then re-run this script.")
    return

  # Step 3: score every row (residual error for distance questions, true/false (on/off mask) for pointing questions)
  scored_columns = df.apply(evaluate_row, axis=1)

  # Step 4: fill the existing "Residual Error"/"Point on Mask?" columns in place 
  # They're already present as empty columns in this CSV, so assign directly 
  df[["Residual Error", "Point on Mask?"]] = scored_columns

  # Step 5: save the scored CSV
  output_path = args.output or f"{Path(args.csv).stem}_scored.csv"
  df.to_csv(output_path, index=False)
  print(f"\nScored CSV saved to {output_path}")

  # Step 6: print summary stats for distance questions.
  # Mean absolute error alone is a weak summary here: it's dragged around by
  # outliers, and it ignores that ground truth distances span a huge range
  # (0.2-16.58cm in this dataset) where "1cm off" means very different things
  # depending on the question's own scale. Added:
  #   - median absolute PERCENTAGE error: robust to outliers (median) and
  #     scale-normalized (percentage), so it's the best single "how far off
  #     is Gemini, typically" number
  #   - mean SIGNED error: reveals systematic bias (over- vs under-estimating)
  #     that any absolute-error metric discards entirely
  #   - 90th percentile absolute error: "how bad does the worst realistic
  #     case get" without letting one single extreme outlier dominate the
  #     way a plain max would
  distance_errors = df["Residual Error"].dropna()
  if not distance_errors.empty:
    abs_errors = distance_errors.abs()
    mean_abs_error = abs_errors.mean()
    mean_signed_error = distance_errors.mean()
    # relative error needs each row's own ground-truth scale
    ground_truth_values = df.loc[distance_errors.index, "Ground Truth"].apply(parse_result_string)
    percent_errors = (abs_errors / ground_truth_values.abs()) * 100
    median_percent_error = percent_errors.median()
    # 90th percentile
    p90_abs_error = abs_errors.quantile(0.90)

    print(f"\nDistance questions: {len(distance_errors)} scored")
    print(f"  Mean absolute residual error: {mean_abs_error:.2f} cm")
    print(f"  Mean signed residual error: {mean_signed_error:.2f} cm (positive = model underestimates)")
    print(f"  Median absolute percentage error: {median_percent_error:.1f}%")
    print(f"  90th percentile absolute error: {p90_abs_error:.2f} cm")

  # Step 7: print summary stats for pointing questions
  pointing_results = df["Point on Mask?"].dropna()
  if not pointing_results.empty:
    accuracy = pointing_results.mean() * 100
    print(f"Pointing questions: {len(pointing_results)} scored, {accuracy:.1f}% on mask")


if __name__ == "__main__":
  main()



